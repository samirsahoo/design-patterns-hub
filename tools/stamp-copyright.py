#!/usr/bin/env python3
"""Stamp a copyright notice into every Archify diagram under static/diagrams/.

Idempotent: files that already carry the stamp are left unchanged.
Usage: python tools/stamp-copyright.py [hub-root]
"""
import pathlib, sys

OWNER = "Samir Kumar Sahoo"
URL = "https://github.com/samirsahoo"
YEAR = "2026"
MARK = "data-copyright-stamp"

META = (f'<meta name="copyright" content="&copy; {YEAR} {OWNER} ({URL}). All rights reserved.">'
        f'<meta name="author" content="{OWNER}">')
NOTICE = (
    f'<div {MARK} style="position:fixed;left:10px;bottom:6px;z-index:2147483647;'
    'font:11px/1.4 system-ui,-apple-system,Segoe UI,sans-serif;color:#64748b;'
    'background:rgba(127,127,127,.10);padding:2px 8px;border-radius:6px;pointer-events:auto">'
    f'&copy; {YEAR} <a href="{URL}" target="_blank" rel="noopener" style="color:inherit">{OWNER}</a>. '
    'All rights reserved.</div>'
)
COMMENT = (f"<!-- Copyright (c) {YEAR} {OWNER} ({URL}). All rights reserved. "
           "Diagram content may not be copied, reproduced or redistributed without written permission. "
           "The embedded viewer runtime is generated by Archify (MIT License). -->")

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")
changed = 0
for f in sorted((root / "static" / "diagrams").glob("*.html")):
    s = f.read_text(encoding="utf-8")
    if MARK in s:
        continue
    head_i = s.lower().find("</head>")
    body_i = s.lower().rfind("</body>")
    if head_i < 0 or body_i < 0:
        print("skip (no head/body):", f)
        continue
    s = s[:body_i] + NOTICE + s[body_i:]
    s = s[:head_i] + META + s[head_i:]
    if s.lower().startswith("<!doctype"):
        nl = s.find(">") + 1
        s = s[:nl] + "\n" + COMMENT + s[nl:]
    else:
        s = COMMENT + "\n" + s
    f.write_text(s, encoding="utf-8", newline="\n")
    changed += 1
print(f"stamped {changed} diagram(s) in {root}")
